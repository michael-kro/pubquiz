#!/usr/bin/env node
// Builds single-file programs (no Node install needed) into dist/, one per platform:
//   node scripts/build-binaries.mjs                 all platforms
//   node scripts/build-binaries.mjs macos-arm64     just the ones named
// The pages and sample quiz are baked in. Needs internet the first time, to fetch each platform's runtime.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const EMBEDDED = join(ROOT, 'server', 'embedded.ts');
const DIST = join(ROOT, 'dist');

const TARGETS = {
  'macos-arm64': { bun: 'bun-darwin-arm64', file: 'pubquiz-macos-arm64' },
  'macos-x64': { bun: 'bun-darwin-x64', file: 'pubquiz-macos-x64' },
  'linux-x64': { bun: 'bun-linux-x64', file: 'pubquiz-linux-x64' },
  'linux-arm64': { bun: 'bun-linux-arm64', file: 'pubquiz-linux-arm64' },
  'windows-x64': { bun: 'bun-windows-x64', file: 'pubquiz-windows-x64.exe' },
};

const wanted = process.argv.slice(2);
const names = wanted.length ? wanted : Object.keys(TARGETS);
for (const name of names) {
  if (!TARGETS[name]) {
    console.error(`Unknown target "${name}". Choose from: ${Object.keys(TARGETS).join(', ')}`);
    process.exit(1);
  }
}

const stub = await readFile(EMBEDDED, 'utf8');
const { listEmbeddable } = await import('../server/assets.ts');
const files = Object.fromEntries(
  await Promise.all((await listEmbeddable()).map(async ([key, path]) => [key, (await readFile(path)).toString('base64')])),
);

await mkdir(DIST, { recursive: true });
const sums = [];
try {
  await writeFile(
    EMBEDDED,
    `// Generated by scripts/build-binaries.mjs. Do not commit.\nexport const EMBEDDED: Record<string, string> = ${JSON.stringify(files)};\n`,
  );
  for (const name of names) {
    const { bun, file } = TARGETS[name];
    const out = join(DIST, file);
    console.log(`Building ${file}…`);
    const result = spawnSync(
      join(ROOT, 'node_modules', '.bin', 'bun'),
      ['build', '--compile', `--target=${bun}`, '--minify', '--outfile', out, join(ROOT, 'server', 'main.ts')],
      { stdio: 'inherit', cwd: ROOT },
    );
    if (result.status !== 0) {
      console.error(`Building ${file} failed.`);
      process.exitCode = 1;
      continue;
    }
    sums.push(`${createHash('sha256').update(await readFile(out)).digest('hex')}  ${file}`);
  }
} finally {
  await writeFile(EMBEDDED, stub); // Back to the empty list, so source runs read files from disk.
}
if (sums.length) {
  await writeFile(join(DIST, 'SHA256SUMS'), sums.join('\n') + '\n');
  console.log(`\nDone. See dist/ (checksums in dist/SHA256SUMS).`);
}
